// Teste do robô no simulador do Firebase (Cloud Shell): grava dados de mentira, roda o robô duas vezes e confere o que ele mandaria.
// Rodar (dentro de testes/):  npx firebase emulators:exec --only firestore --project demo-portal "node ../robo/teste-emulador.mjs"
import { initializeApp } from "firebase-admin/app";
import { getFirestore, Timestamp } from "firebase-admin/firestore";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
const aqui = path.dirname(fileURLToPath(import.meta.url));
process.env.GCLOUD_PROJECT = "demo-portal";
initializeApp({ projectId: "demo-portal" });
const db = getFirestore();
let ok = 0, falha = 0;
const check = (n, c, x) => { if (c) { ok++; console.log("PASS", n); } else { falha++; console.log("FAIL", n, x || ""); } };
const robo = () => execFileSync("node", [path.join(aqui, "avisos.mjs")], { env: { ...process.env, FIREBASE_SERVICE_ACCOUNT: "" }, encoding: "utf8" });
const agora = Date.now();
const lote = db.batch();
[["adm", "admin"], ["ti1", "time"], ["rep1", "representante"], ["rep2", "representante"]].forEach(([id, papel]) => lote.set(db.doc("perfis/" + id), { papel, situacao: "aprovado", nome: id, siglaPrincipal: papel === "representante" ? "CPQ" : "" }));
lote.set(db.doc("acessos/rep1_CPQ"), { uid: "rep1", sigla: "CPQ", situacao: "aprovado", principal: true });
lote.set(db.doc("acessos/rep2_CPQ"), { uid: "rep2", sigla: "CPQ", situacao: "aprovado", principal: true });
lote.set(db.doc("unidades/CPQ"), { sigla: "CPQ", regiao: "Sudeste", dono_uid: "rep1" });
lote.set(db.doc("config/carteiras"), { regioes: { Sudeste: { uid: "ti1", nome: "Ana" } } });
lote.set(db.doc("avisos/rep1"), { tokens: ["tok-rep1"] });
lote.set(db.doc("avisos/ti1"), { tokens: ["tok-ti1a", "tok-ti1b"] });
lote.set(db.doc("pedidos/CPQ-ANTIGO"), { sigla: "CPQ", regiao: "Sudeste", situacao: "Nova", criada_em: Timestamp.fromMillis(agora - 3600000), enviada_em: null, leads: {} });
await lote.commit();
let saida = robo();
check("primeira execução não manda nada", /Primeira execução/.test(saida), saida);
check("robô gravou o estado", (await db.doc("robo_avisos/estado").get()).exists);
await db.doc("pedidos/CPQ-NOVO").set({ sigla: "CPQ", regiao: "Sudeste", cidade_uf: "Campinas/SP", situacao: "Nova", solicitante: "rep1", segmentos: ["Farmácias"], criada_em: Timestamp.now(), enviada_em: null, leads: {} });
await db.doc("pedidos/CPQ-ANTIGO").update({ situacao: "Enviada", enviada_em: Timestamp.now(), leads: { a: { status: "Novo" }, b: { status: "Novo" } } });
await db.doc("perfis/novo").set({ papel: "representante", situacao: "pendente", siglaPrincipal: "CPQ", cargo: "Representante" });
saida = robo();
const sim = JSON.parse((saida.match(/SIMULADOS (.*)/) || [])[1] || "[]");
const tipo = (t) => sim.find(x => x.tipo === t);
check("pedido novo para quem cuida do Sudeste (2 aparelhos)", tipo("novo-pedido") && tipo("novo-pedido").uids.join() === "ti1" && tipo("novo-pedido").aparelhos === 2, saida);
check("leads chegaram para a unidade", tipo("leads-chegaram") && tipo("leads-chegaram").uids.sort().join() === "rep1,rep2" && tipo("leads-chegaram").aparelhos === 1, saida);
check("cadastro novo para admin e dono", tipo("cadastro") && tipo("cadastro").uids.sort().join() === "adm,rep1", saida);
saida = robo();
check("terceira execução não repete", /Avisos decididos: 0\./.test(saida), saida);
check("log sem nomes nem endereços", !/tok-|rep1|ti1|Campinas/.test(saida.replace(/SIMULADOS.*/, "")), saida);
console.log(`${ok} passaram, ${falha} falharam`); process.exit(falha ? 1 : 0);
